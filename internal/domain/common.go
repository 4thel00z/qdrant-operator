var quantityPattern = regexp.MustCompile(`^([0-9]+(?:\.[0-9]+)?)(Ki|Mi|Gi|Ti|Pi|Ei|k|M|G|T|P|E)?$`)

var quantityFactors = map[string]int64{
	"":   1,
	"Ki": 1 << 10,
	"Mi": 1 << 20,
	"Gi": 1 << 30,
	"Ti": 1 << 40,
	"Pi": 1 << 50,
	"Ei": 1 << 60,
	"k":  1e3,
	"M":  1e6,
	"G":  1e9,
	"T":  1e12,
	"P":  1e15,
	"E":  1e18,
}

// ParseQuantity returns the bytes in a Kubernetes storage quantity such as 10Gi or 500M, rounded up.
func ParseQuantity(value string) (int64, error) {
	match := quantityPattern.FindStringSubmatch(value)
	if match == nil {
		return 0, fmt.Errorf("not a storage quantity: %q", value)
	}
	number, ok := new(big.Rat).SetString(match[1])
	if !ok {
		return 0, fmt.Errorf("not a storage quantity: %q", value)
	}
	bytes := number.Mul(number, new(big.Rat).SetInt64(quantityFactors[match[2]]))
	quotient, remainder := new(big.Int).QuoRem(bytes.Num(), bytes.Denom(), new(big.Int))
	if remainder.Sign() != 0 {
		quotient.Add(quotient, big.NewInt(1))
	}
	if !quotient.IsInt64() {
		return 0, fmt.Errorf("storage quantity out of range: %q", value)
	}
	return quotient.Int64(), nil
}

// MergeJSON deep-merges maps left to right; later layers win on scalar conflicts.
func MergeJSON(layers ...JSON) JSON {
	merged := JSON{}
	for _, layer := range layers {
		for key, value := range layer {
			current, currentIsMap := merged[key].(JSON)
			incoming, incomingIsMap := value.(JSON)
			if currentIsMap && incomingIsMap {
				merged[key] = MergeJSON(current, incoming)
				continue
			}
			merged[key] = value
		}
	}
	return merged
}
